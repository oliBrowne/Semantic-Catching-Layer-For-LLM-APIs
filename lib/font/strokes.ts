/**
 * A monoline handwriting alphabet.
 *
 * Every glyph is described the way a pen would draw it: one or more strokes,
 * each a run of points the nib passes through. This is deliberately *not* an
 * outline font. Animating `stroke-dashoffset` on an outline traces the
 * silhouette of a letter, which reads as a machine tracing a shape. Tracing a
 * skeleton reads as a hand writing.
 *
 * Coordinate system (SVG convention, y grows downward):
 *
 *   y = -100  ascender
 *   y =  -92  cap height
 *   y =  -48  x-height
 *   y =    0  baseline
 *   y =  +36  descender
 *
 * Points are written as "x,y x,y x,y" and smoothed into cubic beziers at
 * runtime (see lib/handwriting/path.ts), so the data stays readable and
 * editable by hand.
 */

export type Glyph = {
  /** How far the pen travels before the next glyph starts. */
  advance: number;
  /** Ordered strokes; the pen lifts between them. */
  strokes: number[][];
};

export const METRICS = {
  ascender: -100,
  capHeight: -92,
  xHeight: -48,
  baseline: 0,
  descender: 36,
  /** One em, used to convert design units to pixels. */
  em: 100,
} as const;

function parse(spec: string): number[] {
  const out: number[] = [];
  for (const pair of spec.trim().split(/\s+/)) {
    const [x, y] = pair.split(',');
    out.push(Number(x), Number(y));
  }
  return out;
}

function g(advance: number, ...specs: string[]): Glyph {
  return { advance, strokes: specs.map(parse) };
}

